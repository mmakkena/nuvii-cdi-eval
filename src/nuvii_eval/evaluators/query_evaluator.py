"""
CDI query quality evaluator.

Evaluates the quality of provider queries generated by the Nuvii CDI Agent,
focusing on non-leading language, clinical accuracy, and ACDIS compliance.
"""

import re
from typing import Any

from nuvii_eval.datasets.schemas import QueryTestCase
from nuvii_eval.evaluators.base import BaseEvaluator, EvalResult, EvalScore
from nuvii_eval.schemas.api_responses import ProviderQuery


# =============================================================================
# Query Quality Patterns
# =============================================================================

# Leading language patterns to AVOID (indicate assumption of diagnosis)
LEADING_PATTERNS: list[tuple[str, str]] = [
    (r"\bplease confirm\b", "please_confirm"),
    (r"\bdo you agree\b", "do_you_agree"),
    (r"\bisn't it true\b", "isnt_it_true"),
    (r"\bwouldn't you say\b", "wouldnt_you_say"),
    (r"\bobviously\b", "obviously"),
    (r"\bclearly\b", "clearly"),
    (r"\bdefinitely has\b", "definitely_has"),
    (r"\bmust have\b", "must_have"),
    (r"\bcertainly\b", "certainly"),
    (r"\bundoubtedly\b", "undoubtedly"),
    (r"\bthe patient has\b", "patient_has"),  # Asserts diagnosis
    (r"\bpatient is suffering from\b", "suffering_from"),
    (r"\bconfirm that\b", "confirm_that"),
    (r"\bagree that\b", "agree_that"),
]

# Yes/No question patterns (often leading)
YES_NO_PATTERNS: list[tuple[str, str]] = [
    (r"^(is|are|do|does|did|was|were|has|have|can|could|would|should)\s+", "yes_no_start"),
    (r"\?$", "ends_with_question"),  # Combined with above = yes/no question
]

# ACDIS-compliant patterns (good indicators)
COMPLIANT_PATTERNS: list[tuple[str, str]] = [
    (r"\bplease clarify\b", "please_clarify"),
    (r"\bplease specify\b", "please_specify"),
    (r"\bwhat is the\b", "what_is"),
    (r"\bcould you document\b", "could_document"),
    (r"\bplease indicate\b", "please_indicate"),
    (r"\bbased on.*evidence\b", "based_on_evidence"),
    (r"\bplease review\b", "please_review"),
    (r"\bclinical indicators suggest\b", "indicators_suggest"),
    (r"\bif clinically appropriate\b", "if_appropriate"),
    (r"\bif supported by\b", "if_supported"),
]

# Evidence citation patterns
EVIDENCE_PATTERNS: list[tuple[str, str]] = [
    (r"\"[^\"]+\"", "quoted_evidence"),  # Quoted text
    (r"per (the )?(note|documentation|record)", "per_documentation"),
    (r"documented (on|in|as)", "documented_reference"),
    (r"chart (shows|indicates|notes)", "chart_reference"),
]


def compile_patterns(patterns: list[tuple[str, str]]) -> list[tuple[re.Pattern, str]]:
    """Compile a list of regex patterns."""
    return [(re.compile(p, re.IGNORECASE), name) for p, name in patterns]


# Pre-compile patterns
COMPILED_LEADING = compile_patterns(LEADING_PATTERNS)
COMPILED_YES_NO = compile_patterns(YES_NO_PATTERNS)
COMPILED_COMPLIANT = compile_patterns(COMPLIANT_PATTERNS)
COMPILED_EVIDENCE = compile_patterns(EVIDENCE_PATTERNS)


class QueryEvaluator(BaseEvaluator[QueryTestCase, ProviderQuery]):
    """
    Evaluates CDI query quality using a rubric-based approach.

    Rubric Dimensions:
        - non_leading (25%): Query doesn't assume diagnosis
        - clinical_accuracy (25%): Correct condition and evidence
        - actionability (20%): Clear, specific ask
        - compliance (15%): ACDIS-compliant language
        - evidence_grounding (15%): Cites note evidence

    Configuration:
        - rubric_weights: Override default dimension weights
        - use_llm_judge: Enable LLM-based judging (default: False)
        - max_query_length: Maximum acceptable query length
    """

    evaluator_type = "query"
    pass_threshold = 0.7

    # Default rubric weights
    DEFAULT_WEIGHTS = {
        "non_leading": 0.25,
        "clinical_accuracy": 0.25,
        "actionability": 0.20,
        "compliance": 0.15,
        "evidence_grounding": 0.15,
    }

    def _setup(self) -> None:
        """Initialize evaluator configuration."""
        self.weights = {
            **self.DEFAULT_WEIGHTS,
            **self.config.get("rubric_weights", {}),
        }
        self.use_llm_judge = self.config.get("use_llm_judge", False)
        self.max_query_length = self.config.get("max_query_length", None)

    def evaluate(
        self,
        test_case: QueryTestCase,
        response: ProviderQuery,
    ) -> EvalResult:
        """
        Evaluate query quality against rubric criteria.

        Args:
            test_case: Test case with quality criteria
            response: Generated provider query

        Returns:
            EvalResult with query quality metrics
        """
        query_text = response.query_text
        criteria = test_case.quality_criteria

        # Evaluate each rubric dimension
        non_leading_score, non_leading_details = self._evaluate_non_leading(query_text)
        clinical_score = self._evaluate_clinical_accuracy(
            query_text, test_case.gap.condition, criteria.must_mention
        )
        actionability_score = self._evaluate_actionability(
            query_text, response.suggested_responses, response.icd_impact
        )
        compliance_score, compliance_details = self._evaluate_compliance(query_text)
        evidence_score = self._evaluate_evidence_grounding(
            response.evidence_cited, criteria.min_evidence_citations
        )

        # Check forbidden terms
        forbidden_score, forbidden_details = self._check_forbidden_terms(
            query_text, criteria.must_not_mention
        )

        # Check query length
        length_score = 1.0
        if self.max_query_length and len(query_text) > self.max_query_length:
            length_score = self.max_query_length / len(query_text)

        # Check query type if expected
        type_score = 1.0
        if criteria.expected_query_type:
            type_score = 1.0 if response.query_type == criteria.expected_query_type else 0.5

        scores = [
            EvalScore(
                name="non_leading",
                value=non_leading_score,
                weight=self.weights["non_leading"],
                details=non_leading_details,
            ),
            EvalScore(
                name="clinical_accuracy",
                value=clinical_score,
                weight=self.weights["clinical_accuracy"],
            ),
            EvalScore(
                name="actionability",
                value=actionability_score,
                weight=self.weights["actionability"],
                details={
                    "has_options": len(response.suggested_responses) > 0,
                    "shows_icd_impact": len(response.icd_impact) > 0,
                },
            ),
            EvalScore(
                name="compliance",
                value=compliance_score,
                weight=self.weights["compliance"],
                details=compliance_details,
            ),
            EvalScore(
                name="evidence_grounding",
                value=evidence_score,
                weight=self.weights["evidence_grounding"],
                details={"evidence_count": len(response.evidence_cited)},
            ),
            EvalScore(
                name="no_forbidden_terms",
                value=forbidden_score,
                weight=0.5,  # Penalty weight
                details=forbidden_details,
            ),
            EvalScore(
                name="query_type_match",
                value=type_score,
                weight=0.3,
            ),
            EvalScore(
                name="length_score",
                value=length_score,
                weight=0.2,
            ),
        ]

        # Add reference query comparison if available
        if test_case.reference_query:
            reference_score = self._compare_to_reference(
                query_text, test_case.reference_query
            )
            scores.append(
                EvalScore(
                    name="reference_similarity",
                    value=reference_score,
                    weight=0.3,
                )
            )

        return self._create_result(
            test_case,
            scores,
            details={
                "query_text": query_text[:500],
                "query_type": response.query_type,
                "query_length": len(query_text),
                "evidence_count": len(response.evidence_cited),
                "option_count": len(response.suggested_responses),
            },
        )

    def _evaluate_non_leading(self, query_text: str) -> tuple[float, dict[str, Any]]:
        """
        Check for leading language.

        Returns higher score for absence of leading patterns.

        Args:
            query_text: The query text to evaluate

        Returns:
            Tuple of (score, details)
        """
        violations: list[str] = []

        # Check for leading patterns
        for pattern, name in COMPILED_LEADING:
            if pattern.search(query_text):
                violations.append(name)

        # Check for yes/no framing
        query_lower = query_text.lower().strip()
        has_question = query_text.strip().endswith("?")

        if has_question:
            # Check if starts with yes/no question word
            yes_no_words = ["is", "are", "do", "does", "did", "was", "were", "has", "have", "can", "could", "would", "should"]
            first_word = query_lower.split()[0] if query_lower else ""
            if first_word in yes_no_words:
                violations.append("yes_no_framing")

        # Score: 1.0 with no violations, decreasing by 0.15 per violation
        score = max(0.0, 1.0 - (len(violations) * 0.15))

        return score, {"violations": violations, "violation_count": len(violations)}

    def _evaluate_clinical_accuracy(
        self,
        query_text: str,
        expected_condition: str,
        must_mention: list[str],
    ) -> float:
        """
        Check clinical accuracy of query.

        Verifies that the query mentions the relevant condition and
        required clinical terms.

        Args:
            query_text: The query text
            expected_condition: The condition the query should address
            must_mention: Required terms to mention

        Returns:
            Accuracy score (0.0 to 1.0)
        """
        query_lower = query_text.lower()
        condition_lower = expected_condition.lower()
        score = 0.0

        # Check if condition is mentioned
        condition_words = set(condition_lower.split())
        query_words = set(query_lower.split())

        # Full condition match
        if condition_lower in query_lower:
            score += 0.5
        # Partial condition match (key words)
        elif condition_words & query_words:
            matches = len(condition_words & query_words)
            score += 0.3 * (matches / len(condition_words))

        # Check required terms
        if must_mention:
            mentioned = sum(
                1 for term in must_mention
                if term.lower() in query_lower
            )
            term_score = mentioned / len(must_mention)
            score += 0.5 * term_score
        else:
            score += 0.5  # No required terms = full credit for this portion

        return min(1.0, score)

    def _evaluate_actionability(
        self,
        query_text: str,
        suggested_responses: list[str],
        icd_impact: list[str],
    ) -> float:
        """
        Check if query is actionable.

        Evaluates whether the query has clear asks and options.

        Args:
            query_text: The query text
            suggested_responses: Response options provided
            icd_impact: ICD codes showing impact

        Returns:
            Actionability score (0.0 to 1.0)
        """
        score = 0.0

        # Has suggested response options (preferably 2-4)
        if suggested_responses:
            if 2 <= len(suggested_responses) <= 4:
                score += 0.4
            elif len(suggested_responses) == 1:
                score += 0.2
            else:  # More than 4
                score += 0.3

        # Shows ICD/coding impact
        if icd_impact:
            score += 0.3

        # Has clear ask (question mark or "please")
        if "?" in query_text:
            score += 0.15
        if "please" in query_text.lower():
            score += 0.15

        return min(1.0, score)

    def _evaluate_compliance(self, query_text: str) -> tuple[float, dict[str, Any]]:
        """
        Check ACDIS compliance patterns.

        ACDIS guidelines recommend specific language patterns
        for compliant CDI queries.

        Args:
            query_text: The query text

        Returns:
            Tuple of (score, details)
        """
        matches: list[str] = []

        for pattern, name in COMPILED_COMPLIANT:
            if pattern.search(query_text):
                matches.append(name)

        # Score based on presence of compliant patterns
        if matches:
            # More patterns = better, but cap at 1.0
            score = min(1.0, len(matches) * 0.25)
        else:
            # Neutral if no patterns matched
            score = 0.5

        return score, {"compliant_patterns": matches}

    def _evaluate_evidence_grounding(
        self,
        evidence_cited: list[str],
        min_citations: int,
    ) -> float:
        """
        Check evidence citation quality.

        Args:
            evidence_cited: List of evidence citations
            min_citations: Minimum required citations

        Returns:
            Evidence score (0.0 to 1.0)
        """
        if not evidence_cited:
            return 0.0

        if len(evidence_cited) >= min_citations:
            return 1.0

        # Partial credit for some citations
        return len(evidence_cited) / min_citations

    def _check_forbidden_terms(
        self,
        query_text: str,
        forbidden: list[str],
    ) -> tuple[float, dict[str, Any]]:
        """
        Check for forbidden terms.

        Args:
            query_text: The query text
            forbidden: List of forbidden terms

        Returns:
            Tuple of (score, details)
        """
        if not forbidden:
            return 1.0, {"forbidden_found": []}

        query_lower = query_text.lower()
        found = [
            term for term in forbidden
            if term.lower() in query_lower
        ]

        if not found:
            return 1.0, {"forbidden_found": []}

        # Score decreases with each forbidden term found
        score = max(0.0, 1.0 - (len(found) / len(forbidden)))

        return score, {"forbidden_found": found}

    def _compare_to_reference(
        self,
        query_text: str,
        reference: str,
    ) -> float:
        """
        Compare generated query to reference query.

        Uses simple token overlap for similarity.

        Args:
            query_text: Generated query
            reference: Reference query

        Returns:
            Similarity score (0.0 to 1.0)
        """
        query_tokens = set(query_text.lower().split())
        ref_tokens = set(reference.lower().split())

        if not query_tokens or not ref_tokens:
            return 0.0

        intersection = len(query_tokens & ref_tokens)
        union = len(query_tokens | ref_tokens)

        return intersection / union if union > 0 else 0.0


class QueryEvaluatorStrict(QueryEvaluator):
    """
    Strict query evaluator with higher standards.

    Zero tolerance for leading language, requires more evidence.
    """

    evaluator_type = "query_strict"
    pass_threshold = 0.8

    def _setup(self) -> None:
        """Initialize with strict settings."""
        super()._setup()
        # Any leading pattern = fail
        self.weights["non_leading"] = 0.35


class QueryEvaluatorLenient(QueryEvaluator):
    """
    Lenient query evaluator for development.

    More forgiving on compliance patterns.
    """

    evaluator_type = "query_lenient"
    pass_threshold = 0.6

    def _setup(self) -> None:
        """Initialize with lenient settings."""
        super()._setup()
        self.weights["compliance"] = 0.10
        self.weights["evidence_grounding"] = 0.10
