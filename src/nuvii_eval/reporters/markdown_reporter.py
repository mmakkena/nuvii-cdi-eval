"""
Markdown report generator.

Generates Markdown reports for documentation and PR comments.
"""

from nuvii_eval.reporters.base import BaseReporter, ReportData


class MarkdownReporter(BaseReporter):
    """
    Generates Markdown evaluation reports.

    Creates formatted Markdown suitable for GitHub/GitLab.
    """

    def generate(self, data: ReportData) -> str:
        """Generate Markdown report."""
        sections = [
            self._build_header(data),
            self._build_summary(data),
        ]

        if self.options.include_details:
            sections.append(self._build_details(data))

        sections.append(self._build_footer(data))

        return "\n\n".join(sections)

    def _build_header(self, data: ReportData) -> str:
        """Build header section."""
        status = "PASS" if data.summary.get("pass_rate", 0) >= 70 else "FAIL"
        status_emoji = "" if status == "PASS" else ""

        return f"""# {data.title}

{status_emoji} **Status: {status}**

*Generated: {data.timestamp.strftime("%Y-%m-%d %H:%M:%S")}*"""

    def _build_summary(self, data: ReportData) -> str:
        """Build summary section."""
        s = data.summary

        duration = s.get("duration_seconds")
        duration_str = f"{duration:.1f}s" if duration else "N/A"

        return f"""## Summary

| Metric | Value |
|--------|-------|
| Total Tests | {s.get('total', 0)} |
| Passed | {s.get('passed', 0)} |
| Failed | {s.get('failed', 0)} |
| Pass Rate | {s.get('pass_rate', 0):.1f}% |
| Average Score | {s.get('average_score', 0):.3f} |
| Duration | {duration_str} |"""

    def _build_details(self, data: ReportData) -> str:
        """Build details section."""
        failed_tests = [r for r in data.results if not r.get("pass", True)]

        if not failed_tests:
            return "## Results\n\nAll tests passed!"

        # Group by task type
        by_type = {}
        for result in failed_tests:
            task_type = result.get("metadata", {}).get("task_type", "unknown")
            if task_type not in by_type:
                by_type[task_type] = []
            by_type[task_type].append(result)

        sections = [f"## Failed Tests ({len(failed_tests)})"]

        for task_type, results in sorted(by_type.items()):
            sections.append(f"\n### {task_type.upper()} ({len(results)} failures)")
            sections.append("")
            sections.append("| Test ID | Score | Errors |")
            sections.append("|---------|-------|--------|")

            for result in results[:self.options.max_failures_shown]:
                test_id = result.get("test_id", "unknown")
                score = result.get("score", 0)
                errors = result.get("errors", [])
                error_str = errors[0][:50] + "..." if errors else "-"

                sections.append(f"| {test_id} | {score:.3f} | {error_str} |")

            remaining = len(results) - self.options.max_failures_shown
            if remaining > 0:
                sections.append(f"\n*... and {remaining} more failures*")

        return "\n".join(sections)

    def _build_footer(self, data: ReportData) -> str:
        """Build footer section."""
        return """---

*Generated by Nuvii CDI Evaluation Framework*"""


class PRCommentGenerator:
    """
    Generates concise PR comment summaries.

    Creates compact Markdown suitable for GitHub/GitLab PR comments.
    """

    def __init__(self, max_failures: int = 10):
        """
        Initialize the generator.

        Args:
            max_failures: Maximum failed tests to show
        """
        self.max_failures = max_failures

    def generate(
        self,
        current_data: dict,
        baseline_data: dict | None = None,
    ) -> str:
        """
        Generate PR comment.

        Args:
            current_data: Current evaluation results
            baseline_data: Optional baseline for comparison

        Returns:
            Markdown comment string
        """
        lines = ["## CDI Evaluation Results", ""]

        # Status badge
        stats = current_data.get("stats", {})
        pass_rate = stats.get("pass_rate", 0)
        status = "PASS" if pass_rate >= 70 else "FAIL"
        badge = f"![Status](https://img.shields.io/badge/status-{status}-{'green' if status == 'PASS' else 'red'})"

        lines.append(badge)
        lines.append("")

        # Summary table
        lines.append("| Metric | Value |")
        lines.append("|--------|-------|")
        lines.append(f"| Tests | {stats.get('total', 0)} |")
        lines.append(f"| Passed | {stats.get('passed', 0)} |")
        lines.append(f"| Failed | {stats.get('failed', 0)} |")
        lines.append(f"| Pass Rate | {pass_rate:.1f}% |")

        # Comparison with baseline
        if baseline_data:
            baseline_stats = baseline_data.get("stats", {})
            baseline_rate = baseline_stats.get("pass_rate", 0)
            delta = pass_rate - baseline_rate

            if delta > 0:
                lines.append(f"| vs Baseline | +{delta:.1f}% |")
            elif delta < 0:
                lines.append(f"| vs Baseline | {delta:.1f}% |")
            else:
                lines.append("| vs Baseline | No change |")

        lines.append("")

        # Failed tests
        results = current_data.get("results", [])
        failed = [r for r in results if not r.get("pass", True)]

        if failed:
            lines.append(f"### Failed Tests ({len(failed)})")
            lines.append("")

            for result in failed[:self.max_failures]:
                test_id = result.get("test_id", "unknown")
                score = result.get("score", 0)
                lines.append(f"- `{test_id}` (score: {score:.3f})")

            remaining = len(failed) - self.max_failures
            if remaining > 0:
                lines.append(f"\n*... and {remaining} more*")

            lines.append("")

        # Footer
        lines.append("<details>")
        lines.append("<summary>View full report</summary>")
        lines.append("")
        lines.append("Download the evaluation artifacts for the complete report.")
        lines.append("</details>")

        return "\n".join(lines)
